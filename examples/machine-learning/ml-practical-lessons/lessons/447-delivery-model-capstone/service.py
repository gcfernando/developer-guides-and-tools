"""Serve the locally trained model with input checks. Run the lesson to try it."""

import json
from importlib.metadata import version
from pathlib import Path
from typing import Optional

import joblib
import pandas as pd
from fastapi import FastAPI, HTTPException
from pydantic import BaseModel, FiniteFloat

FOLDER = Path(__file__).resolve().parent


class Delivery(BaseModel):
    distance_km: FiniteFloat
    weight_kg: Optional[FiniteFloat] = None
    zone: str


def read_artifact():
    metadata_path = FOLDER / "model-info.json"
    model_path = FOLDER / "delivery_model.joblib"
    if not metadata_path.is_file() or not model_path.is_file():
        raise RuntimeError("Train the capstone first: python fit_delivery_model.py.")
    info = json.loads(metadata_path.read_text(encoding="utf-8"))
    different = [p for p, saved in info["packages"].items() if version(p) != saved]
    if different:
        raise RuntimeError(
            "Train again in this environment. Package versions differ: "
            + ", ".join(different)
        )
    # joblib can execute code while loading. Use the artifact generated by your own training step.
    return joblib.load(model_path), info


def create_app():
    # 1. Load the fitted artifact once when the local service starts.
    model, info = read_artifact()
    app = FastAPI(title="Practice delivery estimates")

    @app.post("/predict")
    def predict(delivery: Delivery):
        # 2. Reject fields the service cannot use before asking for a prediction.
        if delivery.distance_km < 0:
            raise HTTPException(422, "Enter a nonnegative distance.")
        if delivery.weight_kg is not None and delivery.weight_kg <= 0:
            raise HTTPException(422, "Enter a positive weight or leave it blank.")
        if delivery.zone not in info["known_zones"]:
            raise HTTPException(422, "Choose one of the known zones.")
        if (
            not info["distance_min_km"]
            <= delivery.distance_km
            <= info["distance_max_km"]
        ):
            raise HTTPException(
                422, "That distance is outside the model's training range."
            )
        values = delivery.model_dump()
        if values["weight_kg"] is None:
            values["weight_kg"] = float("nan")
        row = pd.DataFrame([values], columns=info["input_columns"])
        prediction = float(model.predict(row)[0])
        return {"predicted_minutes": round(prediction, 1), "model": info["model"]}

    return app
