const fs=require('node:fs');
const path=require('node:path');
const {ROOT,walk,relative,read,frontMatter,output,yaml}=require('./lib.cjs');
const {parseHTML}=require('linkedom');
const check=process.argv.includes('--check');
const resources=yaml.parse(read('_data/resources.yml'));
const site=yaml.parse(read('_config.yml'));
const routes={'documentation.md':'/documentation/'};
const pages=[];
for(const file of walk()) {
  const name=relative(file);
  if(name.startsWith('maintenance/')||name.startsWith('scripts/')||!name.endsWith('.md')||name==='documentation.md')continue;
  const {data}=frontMatter(read(name));
  pages.push({name,data});
  if(data.permalink)routes[name]=data.permalink;
}
const topics=[...new Set(resources.map(r=>r.topic))];
const topicId=topic=>'catalog-topic-'+topic.toLowerCase().replace(/[^a-z0-9]+/g,'-').replace(/^-|-$/g,'');
const escape=text=>String(text).replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
let result='---\nlayout: default\ntitle: "Developer Documentation and Resource Catalog"\ndescription: "Browse programming courses, cloud and command references, AI and Linux browser tools, developer utilities and configuration examples."\npermalink: /documentation/\n---\n\n# Documentation and resource catalog\n\n<!-- Generated by scripts/build-catalog.cjs from _data/resources.yml and page metadata. -->\n\n[Start here](docs/getting-started.md) · [Learning paths](docs/learning-paths/index.md) · [Interactive tools](apps/README.md) · [Utilities](tools/README.md)\n\nChoose a topic below. On the website, **Search library** also finds guides and tools by title, description or filename. Each resource keeps its own contents, exercises and prerequisites.\n\n<nav aria-label="Catalog topics">\n<ul class="catalog-topics">\n'+topics.map(topic=>'<li><a href="#'+topicId(topic)+'">'+escape(topic)+'</a></li>').join('\n')+'\n</ul>\n</nav>\n\n';
for(const topic of topics) {
  result+='<a id="'+topicId(topic)+'"></a>\n\n';
  result+='## '+topic+'\n\n| Resource | Format | Level |\n|---|---|---|\n';
  for(const r of resources.filter(r=>r.topic===topic)){
    if(!fs.existsSync(path.join(ROOT,r.path)))throw new Error('Missing catalog resource '+r.path);
    const data=r.path.endsWith('.md')?frontMatter(read(r.path)).data:{};
    const title=r.title||data.title;
    if(!title)throw new Error('No title for '+r.path);
    const destination=/\.html?$/i.test(r.path)?new URL(site.baseurl.replace(/\/$/,'')+'/'+r.path,site.url).href:r.path;
    result+='| ['+title.replace(/\|/g,'\\|')+']('+destination+') | '+r.type+' | '+r.level+' |\n';
  }
  result+='\n';
}
result+='## Reading and verification\n\nResources state their own prerequisites and verification limits. Application self-reported progress, example instructions and historical checks are not proof that an exercise ran in your environment.\n\n[Repository overview](README.md) · [Examples](examples/README.md) · [Instruction templates](templates/ai-instructions/README.md)\n';
output('documentation.md',result,check);
// Filesystem enumeration differs across operating systems. Serialize routes in
// JavaScript's locale-independent key order so Windows and Linux agree byte for byte.
const orderedRoutes=Object.fromEntries(Object.keys(routes).sort().map(key=>[key,routes[key]]));
output('_data/routes.json',JSON.stringify(orderedRoutes,null,2)+'\n',check);

// Search is deliberately a metadata index, not an unlabelled partial full-text search.
// Keep it local and reproducible; downloadable templates and private/excluded files
// are not search entries. Existing HTML companions make non-Jekyll guides readable.
const base=site.baseurl.replace(/\/$/,'');
const published=name=>!(site.exclude||[]).some(item=>name===item||name.startsWith(item+'/'));
// SEO noindex does not hide a useful public guide from this library's own search.
const searchable=data=>data.search_exclude!==true;
const indexed=new Map();
const browserURL=(name,data)=>base+(data.permalink||('/'+name));
function topicFor(name) {
  if(name.startsWith('docs/learning-paths/'))return 'Learning paths';
  const related=resources.filter(item=>name.startsWith(path.posix.dirname(item.path)+'/'))
    .sort((a,b)=>path.posix.dirname(b.path).length-path.posix.dirname(a.path).length)[0];
  return related?.topic||'Library';
}
function add(record) {if(!indexed.has(record.url))indexed.set(record.url,record);}
for(const item of resources) {
  if(!published(item.path))continue;
  const data=item.path.endsWith('.md')?frontMatter(read(item.path)).data:{};
  if(!searchable(data))continue;
  add({title:item.title||data.title,description:item.description||data.description||'',topic:item.topic,
    type:item.type,level:item.level||'',source:item.path,url:browserURL(item.path,data)});
}
for(const {name,data} of pages) {
  if(!published(name)||!searchable(data))continue;
  if(data.permalink&&data.title) {
    add({title:data.title,description:data.description||'',topic:topicFor(name),type:name.startsWith('docs/learning-paths/')?'Learning path':'Guide',level:'',source:name,url:browserURL(name,data)});
  } else if(fs.existsSync(path.join(ROOT,name.replace(/\.md$/,'.html')))) {
    const html=name.replace(/\.md$/,'.html');
    const document=parseHTML(read(html)).document;
    const title=(document.querySelector('h1')||document.querySelector('title'))?.textContent?.trim();
    const description=document.querySelector('meta[name="description"]')?.getAttribute('content')||data.description||'';
    if(title)add({title,description,topic:topicFor(name),type:'Browser guide',level:'',source:name,url:base+'/'+html});
  }
}
// The catalog itself was skipped during scanning because it is generated above.
const catalogData=frontMatter(result).data;
add({title:catalogData.title,description:catalogData.description,topic:'Library',type:'Catalog',level:'',source:'documentation.md',url:base+'/documentation/'});
const index=[...indexed.values()].sort((a,b)=>a.title<b.title?-1:a.title>b.title?1:a.url<b.url?-1:a.url>b.url?1:0);
output('assets/data/library-search.json',JSON.stringify(index,null,2)+'\n',check);
console.log((check?'Verified':'Built')+' catalog: '+resources.length+' resources, '+Object.keys(routes).length+' page routes, '+index.length+' searchable destinations.');
