const fs=require('node:fs');
const path=require('node:path');
const {ROOT,walk,relative,read,frontMatter,output,yaml}=require('./lib.cjs');
const check=process.argv.includes('--check');
const resources=yaml.parse(read('_data/resources.yml'));
const routes={'documentation.md':'/documentation/'};
for(const file of walk()) {
  const name=relative(file);
  if(name.startsWith('maintenance/')||name.startsWith('scripts/')||!name.endsWith('.md')||name==='documentation.md')continue;
  const {data}=frontMatter(read(name));
  if(data.permalink)routes[name]=data.permalink;
}
let result='---\nlayout: default\ntitle: "Developer Documentation and Resource Catalog"\ndescription: "Browse programming courses, cloud and command references, AI and Linux browser tools, developer utilities and configuration examples."\npermalink: /documentation/\n---\n\n# Documentation and resource catalog\n\n<!-- Generated by scripts/build-catalog.cjs from _data/resources.yml and page metadata. -->\n\n[Start here](docs/getting-started.md) · [Learning paths](docs/learning-paths/index.md) · [Interactive tools](apps/README.md) · [Utilities](tools/README.md)\n\n';
for(const topic of [...new Set(resources.map(r=>r.topic))]) {
  result+='## '+topic+'\n\n| Resource | Format | Level |\n|---|---|---|\n';
  for(const r of resources.filter(r=>r.topic===topic)){
    if(!fs.existsSync(path.join(ROOT,r.path)))throw new Error('Missing catalog resource '+r.path);
    const data=r.path.endsWith('.md')?frontMatter(read(r.path)).data:{};
    const title=r.title||data.title;
    if(!title)throw new Error('No title for '+r.path);
    result+='| ['+title.replace(/\|/g,'\\|')+']('+r.path+') | '+r.type+' | '+r.level+' |\n';
  }
  result+='\n';
}
result+='## Reading and verification\n\nResources state their own prerequisites and verification limits. Application self-reported progress, example instructions and historical checks are not proof that an exercise ran in your environment.\n\n[Repository overview](README.md) · [Examples](examples/README.md) · [Instruction templates](templates/ai-instructions/README.md)\n';
output('documentation.md',result,check);
output('_data/routes.json',JSON.stringify(routes,null,2)+'\n',check);
console.log((check?'Verified':'Built')+' catalog: '+resources.length+' resources, '+Object.keys(routes).length+' page routes.');
