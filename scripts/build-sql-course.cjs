const fs = require('node:fs');
const path = require('node:path');
const MarkdownIt = require('markdown-it');
const {ROOT, read, frontMatter, output, yaml} = require('./lib.cjs');

const SOURCE = 'docs/databases/sql-server-and-mysql.md';
const DIRECTORY = 'docs/databases/sql-server-and-mysql';
const md = new MarkdownIt({html: true});

function splitCourse(body) {
  const tokens = md.parse(body, {});
  const boundaries = [{slug: '00-start-here', title: 'Start here', line: 0}];
  for (let i = 0; i < tokens.length; i++) {
    if (tokens[i].type !== 'heading_open' || tokens[i].tag !== 'h2') continue;
    const match = tokens[i + 1].content.match(/\bPART (\d+) [\u2014-] (.+)$/);
    if (!match) continue;
    const number = Number(match[1]);
    if (number !== boundaries.length) throw new Error('SQL parts must be numbered consecutively from 1.');
    const slug = match[2].toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
    boundaries.push({slug: `${String(number).padStart(2, '0')}-${slug}`, title: `Part ${number}: ${match[2]}`, line: tokens[i].map[0]});
  }
  if (boundaries.length < 2) throw new Error('No SQL course parts found.');
  const lines = body.match(/[^\n]*\n|[^\n]+$/g) || [];
  return boundaries.map((part, i) => ({
    ...part,
    content: lines.slice(part.line, boundaries[i + 1]?.line ?? lines.length).join('')
  }));
}

function rebaseLinks(content) {
  const lines = content.match(/[^\n]*\n|[^\n]+$/g) || [];
  const protectedLines = new Set();
  for (const token of md.parse(content, {})) {
    if (['fence', 'code_block'].includes(token.type)) {
      for (let line = token.map[0]; line < token.map[1]; line++) protectedLines.add(line);
    }
  }
  const rebase = url => {
    if (url.startsWith('#')) return '../sql-server-and-mysql.md' + url;
    if (/^(?:[a-z][a-z0-9+.-]*:|\/)/i.test(url)) return url;
    return '../' + url;
  };
  return lines.map((line, i) => protectedLines.has(i) ? line : line.replace(
    /(`+).*?\1|(\]\()([^\s)]+)|(\b(?:href|src)=["'])([^"']+)/g,
    (match, code, markdown, target, html, attribute) => code ? match : (markdown || html) + rebase(target || attribute)
  )).join('');
}

function generate(check = false) {
  const {data, body} = frontMatter(read(SOURCE));
  const parts = splitCourse(body);
  const expected = new Set(['index.md', ...parts.map(part => part.slug + '.md')]);
  const directory = path.join(ROOT, DIRECTORY);
  if (fs.existsSync(directory)) {
    for (const file of fs.readdirSync(directory)) {
      if (file.endsWith('.md') && !expected.has(file)) throw new Error(`Unexpected SQL reader ${file}; review obsolete output before removing it.`);
    }
  }
  const marker = `<!-- Generated by scripts/build-sql-course.cjs; edit ${SOURCE}. -->\n\n`;
  let index = '# SQL course: read one part at a time\n\n';
  index += '[Full course and original anchors](../sql-server-and-mysql.md) | [SQL learning path](../../learning-paths/sql.md)\n\n';
  index += 'Start with the prerequisites and verification limits, then follow the parts in order. Examples continue the same shop database; keep SQL Server and MySQL syntax separate. These pages reproduce the full course, not a shortened curriculum. Cross-references open the original full-course section.\n\n';
  index += '| Order | Reading page |\n| --- | --- |\n';
  for (const [i, part] of parts.entries()) {
    index += `| ${i} | [${part.title}](${part.slug}.md) |\n`;
    const navigation = [
      '[Part index](index.md)',
      '[Prerequisites](00-start-here.md)',
      i > 0 ? `[Previous](${parts[i - 1].slug}.md)` : '',
      i + 1 < parts.length ? `[Next](${parts[i + 1].slug}.md)` : '',
      '[Full course](../sql-server-and-mysql.md)'
    ].filter(Boolean).join(' | ') + '\n\n';
    const metadata = {
      layout: 'default', title: `SQL course - ${part.title}`,
      description: `SQL Server and MySQL course reading page: ${part.title}. Follow the original examples and prerequisites.`,
      permalink: `${data.permalink}parts/${part.slug}/`, sitemap: false
    };
    output(`${DIRECTORY}/${part.slug}.md`,
      `---\n${yaml.stringify(metadata)}---\n\n${marker}${navigation}${rebaseLinks(part.content)}\n\n${navigation}`, check);
  }
  output(`${DIRECTORY}/index.md`, `---\n${yaml.stringify({
    layout: 'default', title: 'SQL Course Part Index',
    description: 'Read the SQL Server and MySQL course in ordered parts, with prerequisites and links to the complete reference.',
    permalink: `${data.permalink}parts/`
  })}---\n\n${marker}${index}`, check);
  console.log(`${check ? 'Verified' : 'Built'} SQL readers: ${parts.length} ordered pages and one index; full-course source unchanged.`);
}

if (require.main === module) generate(process.argv.includes('--check'));
module.exports = {splitCourse, rebaseLinks};
